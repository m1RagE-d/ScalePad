const pairParts = (value) => value.split(/\s*\/\s*/).map((part) => part.trim());
const comparisonNames = (value) => {
  const match = value.match(/[:：]\s*([^/（(]+?)\s*\/\s*([^（(]+?)(?:\s*[（(]|$)/);
  return match ? [match[1].trim(), match[2].trim()] : pairParts(value);
};

const makeSection = (section, instruction, rows, options, response = 'choice') => rows.map((row) => {
  const item = row[0];
  const parts = pairParts(item);
  let text = `${instruction}\n${item}`;
  let display = text;
  let audioText = text;
  let rowOptions = options;
  let correct = row[1];

  if (section === '动物比较测试') {
    text = '下面有两种动物，哪个更大？';
    display = text;
    rowOptions = [parts[0], parts[1]];
    correct = row[1] === '大' ? parts[1] : parts[0];
    audioText = `${text} ${parts[0]}和${parts[1]}。`;
  } else if (section === '物理细节心理表征测试' || section === '物理细节判断测试') {
    text = `${item}的耳朵是圆的，还是尖的？`;
    display = item;
    audioText = `请判断${text}`;
  } else if (section === '物体对比测试' || section.includes('色彩对比测试')) {
    const colorComparison = section.includes('色彩');
    text = colorComparison ? '下面有两种物体，哪个颜色更浅？' : '下面有两种物体，哪个更大？';
    display = text;
    rowOptions = [parts[0], parts[1]];
    correct = row[1] === '1' ? parts[0] : parts[1];
    audioText = `${text} ${parts[0]}和${parts[1]}。`;
  } else if (section === '形态辨别测试') {
    text = `请比较${parts[0]}和${parts[1]}，并说出它们的区别。`;
    display = `${parts[0]} 和 ${parts[1]}`;
    audioText = text;
  } else if (section === '物体心理表征测试') {
    text = `${item}是高的，还是矮的？`;
    display = item;
    audioText = `请判断${text}`;
  } else if (section === '物体典型颜色回忆测试') {
    text = `请想象${item}，并说出它的典型颜色。`;
    display = item;
    audioText = text;
  } else if (section === '个位数心理表征测试') {
    const loopQuestion = instruction.includes('闭环');
    text = loopQuestion ? `数字 ${item} 有闭环吗？` : `数字 ${item} 有弯曲的地方吗？`;
    display = `数字 ${item}`;
    audioText = `请判断${text}`;
  } else if (section === '多位数心理表征测试') {
    text = `数字 ${item} 有闭环吗？`;
    display = `数字 ${item}`;
    audioText = `请判断${text}`;
  } else if (section === '字母心理构建测试') {
    text = `请根据这个变换构建字母：${item}。应该得到哪个大写字母？`;
    display = '';
    response = 'text';
    rowOptions = [];
    audioText = text;
  } else if (section === '汉字心理表征测试') {
    const dotQuestion = instruction.includes('点');
    text = dotQuestion ? `“${item}”带点“、”吗？` : `“${item}”属于左右结构、上下结构，还是独体结构？`;
    display = '';
    audioText = dotQuestion
      ? `请判断汉字“${item}”是否带点。`
      : `请判断汉字“${item}”属于左右结构、上下结构，还是独体结构。`;
  } else if (section === '词语心理表征测试') {
    text = `“${item}”中有几个字属于左右结构？`;
    display = '';
    audioText = `请判断词语“${item}”中有几个字属于左右结构。`;
  } else if (section.includes('名人面孔心理表征测试')) {
    const names = comparisonNames(item);
    const detail = item.match(/[（(]([^）)]*)[）)]/)?.[1]?.trim() || '哪一位更符合描述';
    text = `想象${names[0]}和${names[1]}，${detail}${detail.includes('谁') ? '' : '的是谁？'}`;
    display = text;
    rowOptions = names;
    correct = row[1] === '1' ? names[0] : names[1];
    audioText = text;
  } else if (section === '空间表征测试' || section === '空间感知测试') {
    text = `${item}：箭头是否指向其中一个点？`;
    display = '';
    audioText = '请观察图片，判断箭头是否指向其中一个点。';
  } else if (section === '时钟测试') {
    text = `想象 ${item} 的钟面，时针和分针位于哪一侧？`;
    display = text;
    rowOptions = ['一左一右', '都在左', '都在右'];
    correct = row[1] === '左' ? '都在左' : row[1] === '右' ? '都在右' : '一左一右';
    audioText = text;
  } else if (section === '城市地理方位判断测试') {
    text = `想象中国地图，${parts[0]}和${parts[1]}，哪一个位于武汉西方？`;
    display = text;
    rowOptions = [parts[0], parts[1]];
    correct = row[1] === '1' ? parts[0] : parts[1];
    audioText = text;
  } else if (section === '颜色名称测试') {
    text = `请说出这个色块的颜色：${item}。`;
    display = item;
    audioText = '请说出这个色块的颜色。';
  } else if (section.includes('阅读测试')) {
    text = `请大声朗读：${item}`;
    display = item;
    audioText = text;
  } else if (section.includes('名人面孔识别测试')) {
    text = '这张面孔是哪位名人？请口头回答。';
    display = item;
    audioText = text;
  }

  return {
    section,
    text,
    display,
    audioText,
    options: response === 'text' ? [] : rowOptions,
    response,
    correct,
    ...(row[2] ? { image: row[2] } : {})
  };
});

